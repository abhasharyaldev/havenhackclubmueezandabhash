import { makeSurface } from './surface.js';

export function labelKey(text) {
  return `lbl_${text.replace(/[^a-zA-Z0-9]+/g, '_').slice(0, 48)}_${text.length}`;
}

export function drawLabel(text, color = '#f6e7c1', outline = '#1a120c') {
  const value = text.toUpperCase();
  const scale = 2;
  const gw = 3 * scale;
  const gh = 5 * scale;
  const gap = scale;
  const w = Math.max(4, value.length * (gw + gap) + 2);
  const h = gh + 4;
  const s = makeSurface(w, h);
  let x = 1;
  for (const ch of value) {
    const rows = GLYPHS[ch] || GLYPHS[' '];
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < 3; rx++) {
        if (row[rx] === '1') {
          s.rect(x + rx * scale, 2 + ry * scale, scale, scale, color);
        }
      }
    });
    x += gw + gap;
  }
  s.outline(outline);
  return s.toCanvas();
}

